def montar_contexto(pergunta, quantidade=3):

    resultados = buscar_contexto(
        pergunta,
        quantidade=quantidade
    )

    partes_contexto = []

    for item in resultados:

        bloco = f"""
Fonte: {item['fonte']}
Página: {item['pagina']}

{item['texto']}
"""

        partes_contexto.append(bloco.strip())

    contexto_final = "\n\n---\n\n".join(partes_contexto)

    return contexto_final


