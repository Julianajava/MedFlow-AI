def interface_medflow(pergunta):

    if not pergunta or not pergunta.strip():
        return "⚠️ Digite uma pergunta para consultar a base de conhecimento."

    try:

        # 1. Recupera somente o melhor trecho
        resultados = buscar_contexto(
            pergunta,
            quantidade=1
        )

        melhor = resultados[0]

        contexto = f"""
Fonte: {melhor['fonte']}
Página: {melhor['pagina']}

{melhor['texto']}
"""

        # 2. Prompt curto
        prompt = f"""
Você é o MedFlow AI.

Responda somente com base no contexto abaixo.

Regras:
- Não invente informações.
- Seja claro e objetivo.
- Se a resposta não estiver no contexto, diga:
"Não encontrei essa informação na base de conhecimento."
- Não faça diagnóstico ou prescrição.
- Informe a fonte ao final.

CONTEXTO:
{contexto}

PERGUNTA:
{pergunta}

RESPOSTA:
"""

        # 3. Modelo otimizado para baixa latência
        resposta = client_gemini.models.generate_content(
            model="gemini-3.5-flash-lite",
            contents=prompt
        )

        if not resposta.text:
            return "⚠️ Não foi possível gerar uma resposta."

        return f"""
### 🤖 MedFlow AI

{resposta.text}

---
*Resposta baseada na documentação disponível.*
"""

    except Exception as erro:

        print("ERRO COMPLETO:", repr(erro))

        return f"""
### ❌ Não foi possível concluir a consulta

**Tipo do erro:** `{type(erro).__name__}`

**Detalhe:** `{str(erro)}`

Tente novamente.
"""


